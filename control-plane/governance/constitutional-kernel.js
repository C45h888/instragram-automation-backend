// 7b. Worker Registry — canonical FSM→worker binding
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Register a worker under a domain FSM.
 * Validates the worker contract at registration time (fail-fast).
 *
 * @param {string} fsmName — domain FSM name
 * @param {string} workerName — unique worker identifier
 * @param {object} worker — worker module (must export execute())
 */
function registerWorker(fsmName, workerName, worker) {
  if (!fsmName || typeof fsmName !== 'string') {
    throw new Error('[constitutional-kernel] registerWorker requires a valid fsmName');
  }
  if (!workerName || typeof workerName !== 'string') {
    throw new Error('[constitutional-kernel] registerWorker requires a valid workerName');
  }
  if (!worker || typeof worker !== 'object') {
    throw new Error(`[constitutional-kernel] registerWorker requires a worker object for '${workerName}'`);
  }
  if (typeof worker.execute !== 'function') {
    throw new Error(
      `[constitutional-kernel] Worker '${workerName}' violates contract: missing execute()`
    );
  }
  if (!_domains.has(fsmName)) {
    throw new Error(
      `[constitutional-kernel] Cannot register worker '${workerName}': FSM '${fsmName}' not registered`
    );
  }

  if (!_workerRegistry.has(fsmName)) {
    _workerRegistry.set(fsmName, new Map());
  }
  _workerRegistry.get(fsmName).set(workerName, worker);
  console.log(`[constitutional-kernel] Registered worker '${workerName}' → '${fsmName}'`);
}

/**
 * Resolve a worker by FSM name + worker name.
 * Returns null if not found — caller handles the missing case.
 *
 * @param {string} fsmName
 * @param {string} workerName
 * @returns {object|null} worker module or null
 */
function resolveWorker(fsmName, workerName) {
  const fsmWorkers = _workerRegistry.get(fsmName);
  if (!fsmWorkers) return null;
  return fsmWorkers.get(workerName) || null;
}

/**
 * Return the full worker registry for observability.
 * @returns {Map<string, Map<string, object>>}
 */
function getWorkerRegistry() {
  return _workerRegistry;
}

// ── Worker invocation context tracking ────────────────────────────────────────
// Set during ctx.invokeWorker() execution. Cleared after the worker returns.
// Enables the canonical source gate to recognise events dispatched by workers
// as legitimate — the worker was invoked by CK, so CK vouches for its events.
let _currentWorkerContext = null;

// ═══════════════════════════════════════════════════════════════════════════════
// 8. Dispatch — single entry point for ALL governance events
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Dispatch a runtime event into governance.
 * Routes to the appropriate domain FSM or handles as a global constitutional event.
 *
 * Write order invariant (Lineage-First):
 *   1. Lineage record (commit to canonical ledger)
 *   2. State materialization (mutate runtime state)
 *
 * @param {{ type: string, [key: string]: any }} event
 * @returns {{ allowed: boolean, from?: string, to?: string, lineageId?: string, actionsEmitted?: number, reason?: string }}
 */
function dispatch(event) {
  if (!event || typeof event !== 'object' || typeof event.type !== 'string') {
    return { allowed: false, reason: `event must be { type: string }, got ${typeof event}` };
  }

  // ═══════════════════════════════════════════════════════════════════════════════
  // CANONICAL SOURCE GATE — Central Authority Vector
  // All domain events MUST originate from a canonical source before CK dispatches.
  // Canonical sources:
  //   1. CK coordination cycle  — CK issues lineageId, FSM dispatches own events
  //   2. Internal global events — events CK fires itself (RECONCILIATION_TICK, etc.)
  //
  // Events that bypass this gate (e.g. raw observability writes, malformed events
  // injected directly into the observability plane) are rejected before FSM dispatch.
  // ═══════════════════════════════════════════════════════════════════════════════
  const domainName = DOMAIN_EVENT_MAP[event.type];
  if (domainName) {
    const isInternalDomainEvent = INTERNAL_DOMAIN_EVENTS.has(event.type);
    const hasCanonicalLineage = event.lineageId && typeof event.lineageId === 'string';
    const isWorkerIssued = !!_currentWorkerContext;
    if (!hasCanonicalLineage && !isInternalDomainEvent && !isWorkerIssued) {
      return {
        allowed: false,
        reason: `canonical source required: event '${event.type}' must be issued through ` +
                `CK coordination cycle (lineageId missing)`,
      };
    }
    // If lineageId is present, the event is canonically sourced. Allow
    // cross-domain lineage (e.g. graph-capability FSM dispatching
    // DB_READ_REQUESTED destined for persist-telemetry). The previous
    // strict veto rejected all cross-domain events, which broke the
    // constitutional data-flow chain: any substrate calling
    // _governance.governedRead() or any FSM dispatching a cross-domain
    // request (CAPABILITY_DATA_REQUEST, DB_READ_COMPLETE) was silently
    // rejected, and the chain stalled end-to-end. The lineageId is the
    // canonical-source proof; the lineageDomain is a label of the issuer
    // domain, not a constraint on the target. (Phase 7 Findings, B1)
    //
    // The veto is still enforced when the lineage claims a domain that
    // is not registered as a constitutional citizen — that catches
    // external noise with a fake lineageDomain.
    if (hasCanonicalLineage && event.lineageDomain && !_domains.has(event.lineageDomain)) {
      return {
        allowed: false,
        reason: `cross-domain lineage veto: event for domain '${domainName}' carries ` +
                `lineageId from unknown source domain '${event.lineageDomain}' — not a registered citizen`,
      };
    }
  }

  // ── Route to domain FSM ────────────────────────────────────────────────
  if (domainName) {
    const fsm = _domains.get(domainName);
    if (!fsm) {
      return { allowed: false, reason: `domain '${domainName}' not registered for event ${event.type}` };
    }

    const ctx = {
      fsmName: domainName,
      validate: (from, to, evt) => validateDomainTransition(domainName, from, to, evt),
      dispatchGlobal: (globalEvent) => dispatch(globalEvent),
      // NOTE: getGlobalState is reserved for Phase 6 ctx.getPolicy() integration.
      // Domain FSMs will query constitutional policy context via getGlobalState()
      // when POLICY_BROADCAST is implemented and ctx.getPolicy() is added.
      getGlobalState: () => _currentState,
      // ctx.governedRead — constitutional read interface. Domain FSMs
      // call ctx.governedRead(readDomain, params) to fetch data through
      // the persist-telemetry-fsm reading substrate. The read is
      // gated (whitelist) and observable. (Phase 1+2 — used by
      // acquisition-fsm to hydrate webhook event context before
      // dispatching DB_WRITE_REQUESTED to the persist-telemetry-fsm.)
      governedRead: (readDomain, params) => governedRead(readDomain, params),
      // ctx.sanityCheck — the universal gate for every FSM.
      // (Item a — this turn.) The ctx is the canonical interface.
      // FSMs that need a sanity check call ctx.sanityCheck(action)
      // during their evaluation. CK runs the extension + own check
      // composition. The FSM does NOT need a module-level reference.
      sanityCheck: (action) => sanityCheck(domainName, action),
      // ctx.getWorkerRegistry — introspection for observability
      getWorkerRegistry: () => _workerRegistry,
      // ctx.invokeWorker — the CTX gate for worker invocation.
      // Three checks: ownership, contract, sanity. The FSM never
      // calls a worker directly — every invocation flows through
      // this gate. The gate validates before executing.
      invokeWorker: async (workerName, params) => {
        // Gate 1 — ownership: is this worker registered to this FSM?
        const fsmWorkers = _workerRegistry.get(domainName);
        const worker = fsmWorkers ? fsmWorkers.get(workerName) : null;
        if (!worker) {
          throw new Error(
            `[CK:gate] Worker '${workerName}' not registered for FSM '${domainName}'`
          );
        }
        // Gate 2 — contract: does the worker export execute()?
        if (typeof worker.execute !== 'function') {
          throw new Error(
            `[CK:gate] Worker '${workerName}' violates contract: missing execute()`
          );
        }
        // Gate 3 — sanity: universal system health check
        const check = await sanityCheck(domainName, {
          operation: 'invoke_worker',
          worker: workerName,
          fsm: domainName,
        });
        if (!check.allowed) {
          throw new Error(
            `[CK:gate] Worker '${workerName}' blocked by sanity check: ${check.reason}`
          );
        }
        // Gate passed — invoke with context tracking
        const prevCtx = _currentWorkerContext;
        _currentWorkerContext = { fsmName: domainName, workerName };
        try {
          const _result = await worker.execute(params);
          // Emit WORKER_EXECUTED — records every FSM-invoked worker into
          // the observability plane. The worker-recorder-worker consumes
          // these entries and writes to lineage:worker:entries so the
          // snapshot deriver can count real worker invocations.
          try {
            const obs = _getObservabilityTransition();
            if (obs) {
              obs.transition({
                domain: domainName,
                entity: 'worker_execution',
                entityId: `${domainName}:${workerName}`,
                previousState: null,
                nextState: 'WORKER_EXECUTED',
                authority: 'constitutional-kernel',
                raw: {
                  workerName,
                  domain: domainName,
                  accountId: params?.accountId || null,
                  intentId: params?.intentId || null,
                  outcome: _result?.status || 'completed',
                  invokedAt: Date.now(),
                },
              });
            }
          } catch (_) { /* worker emission is non-critical */ }
          return _result;
        } finally {
          _currentWorkerContext = prevCtx;
        }
      },
    };

    const result = fsm.dispatch(event, ctx);

    // ── Polymorphic await: FSMs may return sync (plain object) or
    //    async (Promise) results. CK awaits Promises transparently.
    if (result && typeof result.then === 'function') {
      return result.then((awaited) => {
        if (awaited.allowed && awaited.actions && awaited.actions.length > 0) {
          _emitActions(awaited.actions);
        }
        return {
          allowed: awaited.allowed,
          from: awaited.from || null,
          to: awaited.to || null,
          lineageId: awaited.lineageId || null,
          actionsEmitted: awaited.allowed && awaited.actions ? awaited.actions.length : 0,
          reason: awaited.reason || null,
        };
      });
    }

    if (result.allowed && result.actions && result.actions.length > 0) {
      _emitActions(result.actions);
    }

    // Domain event lineage is written by the transition writers (consuming from observability plane).
    // CK no longer appends domain events directly to the lineage ledger.
    // Constitutional layer events (global state transitions) are still written by CK.

    return {
      allowed: result.allowed,
      from: result.from || null,
      to: result.to || null,
      lineageId: result.lineageId || null,
      actionsEmitted: result.allowed && result.actions ? result.actions.length : 0,
      reason: result.reason || null,
    };
  }

  // ── Handle as global constitutional event ──────────────────────────────
  const txn = GLOBAL_TRANSITION_MAP[event.type];

  if (!txn) {
    return { allowed: false, reason: `unknown event type: ${event.type}` };
  }

  const from = _currentState;
  const rawTarget = txn.target;
  const target = typeof rawTarget === 'function' ? rawTarget(event, { state: from }) : rawTarget;

  // null target = no state change
  if (target === null) {
    _emitGovernanceTransition(from, from, { intent: event.type, reason: 'no-transition: event recorded' });
    return { allowed: true, from, to: from, actionsEmitted: 0, reason: 'no-transition: event recorded' };
  }

  // Run per-transition guard
  if (txn.guard) {
    const result = txn.guard(event, { state: from });
    if (!result.allowed) {
      _emitGovernanceTransition(from, from, {
        intent: event.type,
        reason: result.reason || 'guard blocked',
        blocked: true,
      });
      return { allowed: false, reason: result.reason || 'guard blocked' };
    }
  }

  // Run general guards
  const generalResults = runGeneralGuards(from, target);
  const failedGeneral = generalResults.find(g => !g.passed);
  if (failedGeneral) {
    _emitGovernanceTransition(from, from, {
      intent: event.type,
      reason: failedGeneral.reason,
      blocked: true,
    });
    return { allowed: false, reason: failedGeneral.reason };
  }

  // Materialize state
  _currentState = target;
  _stateEnteredAt = Date.now();

  // Emit observability transition for global runtime state change
  _emitGovernanceTransition(from, target, {
    intent: event.type,
    substate: event.substate || null,
    reason: event.reason || null,
  });

  // Build actions
  const actions = txn.buildActions ? txn.buildActions(event, { state: from }) : [];

  // Emit actions
  _emitActions(actions);

  console.log(`[constitutional-kernel] ${from} → ${target}  (${event.type})`);

  return {
    allowed: true,
    from,
    to: target,
    actionsEmitted: actions.length,
  };
}

