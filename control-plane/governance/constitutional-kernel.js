/**
 * Register a domain FSM with the constitutional kernel.
 * Initializes the FSM with rehydrated state if lineage was loaded from Redis.
 *
 * @param {object} fsm — domain FSM module
 * @param {object} [extensions] — optional extensions
 * @param {Function} [extensions.sanityCheck] — async permission check
 *   (action) => Promise<{ allowed, reason, alternatives }>. Used by the
 *   FSM during operational decisions (schedule retry, invoke worker).
 *   The ctx.sanityCheck integration is deferred to a later phase.
 * @throws {Error} if fsm is invalid
 */
function registerDomain(fsm, extensions = {}) {
  if (!fsm || typeof fsm !== 'object' || typeof fsm.name !== 'string' || typeof fsm.dispatch !== 'function' || typeof fsm.getState !== 'function' || typeof fsm.exportState !== 'function' || typeof fsm.getHealth !== 'function') {
    throw new Error('[constitutional-kernel] registerDomain requires a valid domain FSM (missing name, dispatch, getState, exportState, or getHealth)');
  }
  _domains.set(fsm.name, fsm);

  // Register domain-specific sanity check extension (if provided)
  if (extensions.sanityCheck && typeof extensions.sanityCheck === 'function') {
    _domainSanityChecks.set(fsm.name, extensions.sanityCheck);
  }

  // ── Wire reading-substrate when persist-telemetry FSM registers ────────
  if (fsm.name === 'persist-telemetry' && typeof fsm.setReadingSubstrate === 'function') {
    readingSubstrate.init({
      governance: module.exports,
      fsm,
    });
    fsm.setReadingSubstrate(readingSubstrate);
    console.log('[constitutional-kernel] Reading substrate wired to persist-telemetry FSM');
  }

  // Initialize domain FSM with rehydrated state from lineage (if available)
  if (_rehydratedDomainStates && typeof fsm.init === 'function') {
    const rehydratedState = _rehydratedDomainStates[fsm.name];
    if (rehydratedState) {
      // init() may be async (e.g. telemetry-coordination-fsm reads Redis-backed cursor).
      // Fire-and-forget is safe here: cursor restoration is idempotent and init is called
      // before any reactive processing begins.
      fsm.init(rehydratedState).catch((err) => {
        console.error(`[constitutional-kernel] Domain '${fsm.name}' init error:`, err.message);
      });
      console.log(`[constitutional-kernel] Domain '${fsm.name}' initialized with rehydrated state: ${rehydratedState}`);
    }
  }

  console.log(`[constitutional-kernel] Registered domain: ${fsm.name}`);
}

