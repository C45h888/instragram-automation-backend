// substrates/webhook-acquisition-substrate/workers/messages-worker.js
// Worker: Instagram DM webhook semantics.
//   - DM echo (entry[].messaging[].message)
//   - DM postback (entry[].messaging[].postback)
//
// Mounted on: substrates/ig-reliability-substrate.js (analyzeFailure).
// Lives in:  acquisition-kernel/substrates/webhook-acquisition-substrate/workers/.
//
// Owns: validates entry[].messaging[] shape, normalizes via the substrate's
//        normalizer, dispatches the canonical event to CK so the
//        acquisition-fsm can hold it. Phase 2 will resolve the staged
//        event into DB_WRITE_REQUESTED.
// Does NOT own: failure classification (bedrock), DB writes, retry policy,
//               state persistence, token storage.
//
// Constitutional contract: workers never classify IG failures directly.
// On any processing error the worker asks the bedrock for an analysis and
// emits the substrate's recommendations through CK.

const { analyzeFailure } =
  require('../../../../substrates/ig-reliability-substrate');
const { normalizeMessaging, EVENT_TYPES } = require('../normalizer');

// ── Validation helpers (semantic shape checks for the worker) ─────────────

function _validateMessagingEntry(item) {
  if (!item || typeof item !== 'object') {
    return { ok: false, reason: 'messaging_item_not_object' };
  }
  if (!item.sender?.id) {
    return { ok: false, reason: 'missing_sender_id' };
  }
  if (!item.recipient?.id) {
    return { ok: false, reason: 'missing_recipient_id' };
  }
  const hasMessage = !!item.message;
  const hasPostback = !!item.postback;
  if (!hasMessage && !hasPostback) {
    return { ok: false, reason: 'messaging_item_has_no_message_or_postback' };
  }
  if (hasMessage && !item.message.mid) {
    return { ok: false, reason: 'missing_message_mid' };
  }
  if (hasPostback && !item.postback.mid) {
    return { ok: false, reason: 'missing_postback_mid' };
  }
  return { ok: true };
}

// ── Worker contract ─────────────────────────────────────────────────────────

/**
 * Execute: process one entry[].messaging[] item into a canonical event
 * and dispatch it into CK for the acquisition-fsm to hold.
 *
 * @param {object} rawItem    — single entry[].messaging[] element
 * @param {string} accountId  — resolved IG account id (from entry.id)
 * @param {string} intentId   — unique intent id generated by the substrate
 * @param {object} governance — constitutional kernel reference
 * @returns {Promise<{ status: string, eventId: string|null, eventType: string }>}
 */
async function execute(rawItem, accountId, intentId, governance) {
  // ── Layer 1: shape validation (semantic, worker-local) ───────────────
  const v = _validateMessagingEntry(rawItem);
  if (!v.ok) {
    return _emitFailure(rawItem, accountId, intentId, v.reason, governance);
  }

  // ── Layer 2: normalize via the substrate's normalizer ───────────────
  let canonical;
  try {
    canonical = normalizeMessaging(rawItem, null);
    canonical.igAccountId = accountId || null;
  } catch (err) {
    return _emitFailure(rawItem, accountId, intentId, `normalizer_threw:${err.message}`, governance);
  }

  // ── Layer 3: dispatch to CK → acquisition-fsm will hold it ───────────
  try {
    if (governance && typeof governance.dispatch === 'function') {
      governance.dispatch({
        type: 'WEBHOOK_EVENT_RECEIVED',
        accountId,
        intentId,
        domain: 'webhook:messages',
        eventType: canonical.eventType,
        eventId: canonical.eventId,
        occurredAt: canonical.occurredAt,
        source: canonical.source,
        priority: canonical.priority,
        normalized: canonical.normalized,
        raw: canonical.raw,
      });
    }
  } catch (err) {
    // Dispatch failure is rare; the substrate is the canonical failure
    // interpreter. We ask it for an analysis rather than classify ourselves.
    return _emitFailure(rawItem, accountId, intentId, `dispatch_threw:${err.message}`, governance);
  }

  return {
    status: 'staged',
    eventId: canonical.eventId,
    eventType: canonical.eventType,
  };
}

// ── Failure emission via the bedrock (no in-worker classification) ─────────

function _emitFailure(rawItem, accountId, intentId, reason, governance) {
  // Build a minimal error envelope for analyzeFailure. The bedrock expects
  // { message } at minimum; the substrate will normalize + classify it.
  const rawError = {
    message: reason,
    source: 'webhook-acquisition:messages',
    eventType: EVENT_TYPES.DM_ECHO,
  };

  let recommendations = [];
  try {
    const analysis = analyzeFailure(rawError, 'webhook:process', 'webhook-acquisition', {
      accountId,
      intentId,
      eventType: 'dm_echo',
    });
    recommendations = analysis?.recommendations || [];
  } catch (_) {
    // Bedrock failure should not block the substrate from emitting a
    // fallback signal. The substrate contract is best-effort.
    recommendations = [];
  }

  if (governance && typeof governance.dispatch === 'function') {
    try {
      governance.dispatch({
        type: 'WEBHOOK_EVENT_DISCARDED',
        accountId,
        intentId,
        domain: 'webhook:messages',
        eventType: EVENT_TYPES.DM_ECHO,
        reason,
        recommendations,
      });
    } catch (_) {
      // Swallow — the failure path is informational.
    }
  }

  return {
    status: 'discarded',
    eventId: null,
    eventType: EVENT_TYPES.DM_ECHO,
    reason,
  };
}

module.exports = { execute };
